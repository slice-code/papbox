#!/bin/sh
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<'SQL'
\getenv app_password PAPBOX_DB_PASSWORD
CREATE ROLE papbox_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS PASSWORD :'app_password';
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT CONNECT ON DATABASE papbox TO papbox_app;
GRANT USAGE ON SCHEMA public TO papbox_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO papbox_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO papbox_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO papbox_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO papbox_app;
DO $$ BEGIN
  IF to_regclass('public.audit_events') IS NOT NULL THEN REVOKE UPDATE, DELETE, TRUNCATE ON audit_events FROM papbox_app; END IF;
  IF to_regclass('public.schema_migrations') IS NOT NULL THEN REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON schema_migrations FROM papbox_app; END IF;
END $$;
SQL
