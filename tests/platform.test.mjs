import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';
import { createApp } from '../server.mjs';
import { Kernel } from '../core/kernel.mjs';
import { Store } from '../core/store.mjs';
import { registerSystem, roles } from '../system/services.mjs';

test('HTTP authentication, authorization, module lifecycle, CSRF, and persistence',async t=>{
 const dir=await mkdtemp(join(tmpdir(),'papbox-')),path=join(dir,'data.json');
 const {server}=createApp({path}); server.listen(0,'127.0.0.1');await once(server,'listening');
 t.after(async()=>{server.closeAllConnections();await new Promise(resolve=>server.close(resolve));await rm(dir,{recursive:true,force:true});});
 const base='http://127.0.0.1:'+server.address().port; let cookie='';
 const request=async(route,data,extra={})=>{const response=await fetch(base+'/api/'+route,{method:data===undefined?'GET':'POST',headers:{'Content-Type':'application/json',Cookie:cookie,...extra},body:data===undefined?undefined:JSON.stringify(data)});return {status:response.status,data:await response.json(),cookie:response.headers.get('set-cookie')};};
 assert.equal((await request('services/launcher.read',{})).status,401);
 assert.equal((await request('setup',{name:'Admin',email:'admin@example.com',password:'short'})).status,400);
 let result=await request('setup',{name:'Admin',email:'admin@example.com',password:'correct horse battery'}); assert.equal(result.status,200); cookie=result.cookie.split(';')[0];
 assert.equal((await request('setup',{name:'Other',email:'other@example.com',password:'another password 123'})).status,409);
 assert.equal((await request('services/settings.save',{name:'Bad'},{Origin:'https://attacker.example'})).status,403);
 assert.equal((await request('services/apps.change',{id:'pos',action:'install'})).status,400);
 assert.equal((await request('services/apps.change',{id:'unknown',action:'install',approved:true})).status,400);
 assert.equal((await request('services/apps.change',{id:'pos',action:'install',approved:true})).status,200);
 assert((await request('services/launcher.read',{})).data.some(a=>a.id==='pos'));
 assert.equal((await request('services/menus.save',{id:'pos',name:'Kasir',order:0,hidden:true})).status,200);
 assert(!(await request('services/launcher.read',{})).data.some(a=>a.id==='pos'));
 await request('services/apps.change',{id:'pos',action:'disable'});
 assert.equal((await request('services/apps.list',{})).data.find(a=>a.id==='pos').enabled,false);
 await request('services/apps.change',{id:'pos',action:'uninstall'});
 assert.equal((await request('services/apps.list',{})).data.find(a=>a.id==='pos').installed,false);
 await request('services/settings.save',{name:'Tim PAPbox'});
 assert.equal((await new Store(path).read()).tenants.default.settings.name,'Tim PAPbox');
 await request('services/users.create',{name:'Member',email:'member@example.com',password:'member password 123',role:'member'});
 assert(!(await request('services/users.list',{})).data.some(u=>'hash' in u));
 await request('logout',{});cookie='';
 result=await request('login',{email:'member@example.com',password:'member password 123'});assert.equal(result.status,200);cookie=result.cookie.split(';')[0];
 assert.equal((await request('services/users.list',{})).status,403);
 assert.deepEqual((await request('services/launcher.read',{})).data.map(a=>a.id),['account']);
 assert.equal((await request('services/apps.change',{id:'pos',action:'install',approved:true})).status,403);
 const page=await fetch(base+'/');assert.equal(page.status,200);assert.match(await page.text(),/PAPbox/);
 for(const asset of ['/manifest.webmanifest','/sw.js','/offline.html','/icon-192.png','/icon-512.png'])assert.equal((await fetch(base+asset)).status,200);
});

test('shared services isolate tenants, deny missing permissions, rollback failures, serialize writes',async t=>{
 const dir=await mkdtemp(join(tmpdir(),'papbox-store-'));t.after(()=>rm(dir,{recursive:true,force:true}));
 const store=new Store(join(dir,'data.json')),kernel=new Kernel();registerSystem(kernel,store);
 await store.transact(s=>{for(const id of ['alpha','beta'])s.tenants[id]={users:[{id:'admin',role:'admin'}],modules:{},menus:{},settings:{name:id},audit:[]};});
 const context=tenant=>({tenant,user:'admin',permissions:roles.admin});
 await kernel.invoke('settings.save',context('alpha'),{name:'Alpha changed'});
 assert.equal((await kernel.invoke('settings.list',context('beta'))).name,'beta');
 await assert.rejects(kernel.invoke('settings.list',{tenant:'alpha',user:'admin',permissions:[]}),{status:403});
 await assert.rejects(kernel.invoke('settings.list',null),{status:401});
 await assert.rejects(store.transact(s=>{s.tenants.alpha.settings.name='broken';throw Error('rollback');}));
 assert.equal((await store.read()).tenants.alpha.settings.name,'Alpha changed');
 await Promise.all(Array.from({length:20},()=>store.transact(s=>{s.count=(s.count||0)+1;})));
 assert.equal((await store.read()).count,20);
});
